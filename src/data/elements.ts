export type ElementCategory =
  | 'nao-metal'
  | 'gas-nobre'
  | 'metal-alcalino'
  | 'metal-alcalino-terroso'
  | 'metaloide'
  | 'halogenio'
  | 'metal-pos-transicao'
  | 'metal-transicao'
  | 'lantanideo'
  | 'actinideo';

export type PhysicalState = 'gas' | 'liquido' | 'solido' | 'desconhecido';
export type ElementOrigin = 'natural' | 'artificial';

export interface ElementData {
  number: number;
  symbol: string;
  name: string;
  atomicMass: number;
  category: ElementCategory;
  categoryLabel: string;
  group: number; // 1-18
  period: number; // 1-7
  gridX: number; // 1-18 coluna na tabela periódica
  gridY: number; // 1-10 linha na tabela periódica (incluindo lantanídeos e actinídeos)
  electronicConfiguration: string;
  electronsPerShell: number[]; // K, L, M, N, O, P, Q
  electronegativity?: number;
  density?: number; // g/cm³ ou g/L
  meltingPoint?: number; // em °C
  boilingPoint?: number; // em °C
  phase: PhysicalState;
  phaseLabel: string;
  origin: ElementOrigin;
  originLabel: string;
  description: string;
  discoverer: string;
  discoveryYear: number | string;
  wikiLink: string;
  importantUses: string[];
  colorHex: string;
}

